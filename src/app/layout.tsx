/**
 * Next merges metadata one level deep, so a page that sets `openGraph` replaces
 * this whole object. Every page spreads it and adds its own title, description
 * and url, or shares lose the image and site name and point og:url at the wrong page.
 */
export const healthyOpenGraph = {
  siteName: "GetBrian Healthy",
  type: "website",
  locale: "en_US",
  images: [{ url: "/healthy/brand/og-image.png", width: 1200, height: 630, alt: "GetBrian Healthy" }],
} satisfies NonNullable<Metadata["openGraph"]>;

export async function generateMetadata(): Promise<Metadata> {
  const region = await getRegion();
  const pageDescription = region === "GB" ? descriptionGb : description;
  return {
  metadataBase: new URL(siteUrl),
  title: {
    default: `${PROGRAM_NAME} | GetBrian Healthy`,
    template: `%s | ${PROGRAM_NAME}`,
  },
  description: pageDescription,
  alternates: { canonical: "/" },
  // Draft figures must not be indexed. See LAUNCHED in data.ts.
  robots: LAUNCHED ? { index: true, follow: true } : { index: false, follow: false },
  openGraph: { ...healthyOpenGraph, title: PROGRAM_NAME, description: pageDescription, url: "/" },
  // Generated by `npm run brand:healthy`. 16 and 32 are both declared so
  // browsers take the exact size match at 1x and 2x.
  icons: {
    icon: [
      { url: "/healthy/brand/favicon-16.png", sizes: "16x16", type: "image/png" },
      { url: "/healthy/brand/favicon-32.png", sizes: "32x32", type: "image/png" },
      { url: "/healthy/brand/icon-512.png", sizes: "512x512", type: "image/png" },
    ],
    apple: [{ url: "/healthy/brand/apple-touch-icon.png", sizes: "180x180" }],
  },
  };
}

